func TestPathSelectionDiscoveryAndBases(t *testing.T) {
	home := t.TempDir()
	configDir := filepath.Join(home, ".config", "harness-model-proxy")
	if err := os.MkdirAll(configDir, 0o755); err != nil {
		t.Fatal(err)
	}
	path := writeConfig(t, configDir, `{"api_keys_file":"relative/keys.json"}`)
	result := load(t, LoadOptions{Getenv: getenv(map[string]string{"HOME": home}), DeriveInstanceID: fixedInstance("instance")})
	if result.Path != path || result.PathExplicit || result.Config.APIKeysFile != filepath.Join(configDir, "relative", "keys.json") {
		t.Fatalf("discovery result = path %q explicit=%v keys=%q", result.Path, result.PathExplicit, result.Config.APIKeysFile)
	}

	result = load(t, LoadOptions{Path: "", PathExplicit: true, Getenv: getenv(map[string]string{"HOME": home}), DeriveInstanceID: fixedInstance("instance")})
	if result.Path != "" || !result.PathExplicit {
		t.Fatalf("explicit empty path discovered config: path=%q explicit=%v", result.Path, result.PathExplicit)
	}

	result = load(t, LoadOptions{Path: path, PathExplicit: true, Flags: parseFlags(t, "-api-keys-file", "cwd-relative.json"), DeriveInstanceID: fixedInstance("instance")})
	if result.Config.APIKeysFile != "cwd-relative.json" || !result.APIKeysFileExplicit || result.Sources["api_keys_file"].Kind != configmeta.SourceFlag {
		t.Fatalf("flag-relative key path = %q explicit=%v source=%+v", result.Config.APIKeysFile, result.APIKeysFileExplicit, result.Sources["api_keys_file"])
	}

	tmp := t.TempDir()
	fallbackDir := filepath.Join(tmp, "harness-model-proxy-config")
	if err := os.MkdirAll(fallbackDir, 0o755); err != nil {
		t.Fatal(err)
	}
	fallbackPath := writeConfig(t, fallbackDir, `{}`)
	result = load(t, LoadOptions{Getenv: getenv(map[string]string{"HOME": "", "TMPDIR": tmp}), DeriveInstanceID: fixedInstance("instance")})
	if result.Path != fallbackPath {
		t.Fatalf("TMPDIR discovery path = %q, want %q", result.Path, fallbackPath)
	}
}


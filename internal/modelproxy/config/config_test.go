func TestSnapshotExposesPathsButNeverReferencedSecrets(t *testing.T) {
	dir := t.TempDir()
	providerPath := filepath.Join(dir, "provider.json")
	keyPath := filepath.Join(dir, "keys.json")
	if err := os.WriteFile(providerPath, []byte(`{"api_key":"sk-super-secret","auth":{"client_secret":"oauth-secret"}}`), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(keyPath, []byte(`{"api_keys":[{"key":"hmp_plain_secret"}]}`), 0o600); err != nil {
		t.Fatal(err)
	}
	path := writeConfig(t, dir, `{"provider_configs":["provider.json"],"api_keys_file":"keys.json"}`)
	result := load(t, LoadOptions{Path: path, PathExplicit: true, DeriveInstanceID: fixedInstance("instance")})
	snapshot := Snapshot(result)
	projection := configmeta.Project(Catalog(), snapshot, true)
	encoded, err := json.Marshal(projection)
	if err != nil {
		t.Fatal(err)
	}
	text := string(encoded)
	for _, secret := range []string{"sk-super-secret", "oauth-secret", "hmp_plain_secret", "api_key\""} {
		if strings.Contains(text, secret) {
			t.Fatalf("snapshot leaked %q: %s", secret, text)
		}
	}
	if !strings.Contains(text, "provider.json") || !strings.Contains(text, "keys.json") {
		t.Fatalf("snapshot omitted safe path references: %s", text)
	}
	snapshot.Values["provider_configs"].([]string)[0] = "mutated"
	if result.Config.ProviderConfigs[0] != "provider.json" {
		t.Fatal("Snapshot aliased provider path list")
	}
}

func parseFlags(t *testing.T, args ...string) cli.Values {
	t.Helper()
	catalog := cli.MustCatalog(cli.Command{ID: "test", Name: "test", Runnable: true, Flags: CLIFlags()})
	invocation, err := catalog.Parse(args)
	if err != nil {
		t.Fatalf("parse flags %v: %v", args, err)
	}
	return invocation.Flags
}

func load(t *testing.T, options LoadOptions) Result {
	t.Helper()
	if options.DeriveInstanceID == nil {
		options.DeriveInstanceID = fixedInstance("test-instance")
	}
	result, err := Load(options)
	if err != nil {
		t.Fatal(err)
	}
	return result
}

func writeConfig(t *testing.T, dir, contents string) string {
	t.Helper()
	path := filepath.Join(dir, "config.json")
	if err := os.WriteFile(path, []byte(contents), 0o600); err != nil {
		t.Fatal(err)
	}
	return path
}

func getenv(values map[string]string) func(string) string {
	return func(name string) string { return values[name] }
}

func fixedInstance(value string) func() (string, error) {
	return func() (string, error) { return value, nil }
}
